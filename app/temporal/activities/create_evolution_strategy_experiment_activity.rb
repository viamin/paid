# frozen_string_literal: true

module Activities
  class CreateEvolutionStrategyExperimentActivity < BaseActivity
    activity_name "CreateEvolutionStrategyExperiment"

    def execute(input)
      account = Account.find(input.fetch(:account_id))
      strategy_snapshot = input.fetch(:strategy).deep_stringify_keys
      strategy_type = strategy_snapshot.fetch("strategy_type")
      candidate_ids = Array(input.fetch(:candidate_ids))

      existing = StrategyExperiment.running.find_by(account: account, strategy_name: strategy_type)
      if existing
        return {
          strategy_experiment_id: existing.id,
          status: :already_running
        }
      end

      candidates = OrchestrationStrategy.where(id: candidate_ids, account: account, strategy_type: strategy_type)
        .order(:version, :id)
      experiment = StrategyExperiments::CreateForCandidates.call(
        account: account,
        strategy_type: strategy_type,
        control_strategy: StrategyExperiments::StrategySnapshot.deserialize(strategy_snapshot, account: account),
        candidate_strategies: candidates,
        min_samples_per_variant: input.fetch(:min_samples_per_variant, 30),
        confidence_threshold: input.fetch(:confidence_threshold, 0.95),
        traffic_percentage: input.fetch(:traffic_percentage, 100),
        description: "Auto-generated by strategy evolution workflow for #{strategy_type}"
      )
      experiment.start!

      {
        strategy_experiment_id: experiment.id,
        status: :created
      }
    end
  end
end

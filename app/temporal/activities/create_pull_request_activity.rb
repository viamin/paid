# frozen_string_literal: true

module Activities
  class CreatePullRequestActivity < BaseActivity
    activity_name "CreatePullRequest"

    def execute(input)
      agent_run_id = input[:agent_run_id]
      agent_run = AgentRun.find(agent_run_id)
      track_phase(agent_run_id: agent_run_id, phase_key: "create_pull_request", phase_group: "post", agent_run: agent_run) do
        project = agent_run.project
        issue = agent_run.issue

        client = project.github_token.client
        pr = client.create_pull_request(
          project.full_name,
          base: project.default_branch,
          head: agent_run.branch_name,
          title: pr_title(issue),
          body: pr_body(issue, agent_run),
          draft: true
        )

        agent_run.complete!(
          result_commit: agent_run.result_commit_sha,
          pr_url: pr.html_url,
          pr_number: pr.number
        )

        add_pr_labels(client, project, pr.number, agent_run_id)

        agent_run.log!("system", "PR created: #{pr.html_url}")

        logger.info(
          message: "agent_execution.pull_request_created",
          agent_run_id: agent_run_id,
          pull_request_url: pr.html_url
        )

        { agent_run_id: agent_run_id, pull_request_url: pr.html_url, pull_request_number: pr.number }
      end
    end

    private

    def pr_title(issue)
      return "Agent changes" unless issue

      "Fix ##{issue.github_number}: #{issue.title}".truncate(255)
    end

    def pr_body(issue, agent_run)
      parts = []

      summary = agent_run.agent_summary
      validate_summary_scope(summary, issue, agent_run)
      description = generate_description(summary, issue, agent_run_id: agent_run.id)

      if description.present?
        parts << description
      else
        parts << fallback_body(issue)
      end

      parts << ""

      if issue
        parts << "---"
        parts << ""
        parts << "Closes ##{issue.github_number}"
      end

      parts.join("\n")
    end

    def fallback_body(issue)
      parts = []
      parts << "## Summary"
      parts << ""

      if issue
        parts << issue.title
        parts << ""
        parts << "See ##{issue.github_number} for context. Paid was unable to auto-generate a description for this PR;"
        parts << "the diff is the authoritative source of truth."
      else
        parts << "This pull request was automatically generated by [Paid](https://github.com/viamin/paid)."
        parts << ""
        parts << "Paid was unable to auto-generate a description for this PR;"
        parts << "the diff is the authoritative source of truth."
      end

      parts.join("\n")
    end

    def generate_description(summary, issue, agent_run_id:)
      return nil if summary.blank?

      Llm::GeneratePrDescription.call(
        agent_summary: summary,
        issue_title: issue&.title,
        issue_body: issue&.body
      )
    rescue StandardError => e
      logger.warn(
        message: "agent_execution.pr_description_failed",
        agent_run_id: agent_run_id,
        issue_number: issue&.github_number,
        error_class: e.class.name,
        error: e.message
      )
      nil
    end

    # Checks whether the agent summary text plausibly relates to the target
    # issue.  Logs a structured warning when the summary appears to describe
    # a *different* issue — the most visible symptom of cross-run state
    # contamination (see GitHub issue #905).
    #
    # The check is deliberately lightweight (string matching, no LLM call)
    # so it never blocks PR creation.
    def validate_summary_scope(summary, issue, agent_run)
      return if summary.blank? || issue.nil?

      issue_number = issue.github_number

      mentions_own_issue = summary.match?(/(?<!\w)##{issue_number}\b/) ||
                          summary.match?(/\bissue\s+#{issue_number}\b/i)

      # Extract all #NNN references from the summary in a single pass, then
      # intersect with sibling open issues to avoid O(issues × summary) regex.
      referenced_numbers = summary.scan(/(?<!\w)#(\d+)\b/).flatten.map(&:to_i).to_set
      referenced_numbers.delete(issue_number)

      sibling_numbers = sibling_open_issue_numbers(agent_run.project, exclude: issue_number).to_set
      cross_refs = referenced_numbers.intersection(sibling_numbers).to_a.sort

      if !mentions_own_issue && cross_refs.any?
        logger.warn(
          message: "agent_execution.summary_scope_mismatch",
          agent_run_id: agent_run.id,
          issue_number: issue_number,
          cross_referenced_issues: cross_refs,
          summary_preview: summary.truncate(200)
        )
        agent_run.log!(
          "system",
          "Warning: agent summary may describe a different issue. " \
          "Expected references to ##{issue_number}, found references to: #{cross_refs.map { |n| "##{n}" }.join(", ")}"
        )
      end
    end

    # Returns github_numbers of other open issues in the same project,
    # excluding the current issue.
    def sibling_open_issue_numbers(project, exclude:)
      project.issues
        .where(github_state: "open", is_pull_request: false)
        .where.not(github_number: exclude)
        .pluck(:github_number)
    end

    def add_pr_labels(client, project, pr_number, agent_run_id)
      return unless project.auto_add_labels_enabled?

      client.add_labels_to_issue(project.full_name, pr_number, [
        project.generated_label_name,
        project.automation_label_name
      ])
    rescue GithubClient::Error => e
      logger.warn(
        message: "agent_execution.add_pr_labels_failed",
        agent_run_id: agent_run_id,
        pr_number: pr_number,
        error: e.message
      )
    end
  end
end

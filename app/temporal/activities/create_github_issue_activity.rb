# frozen_string_literal: true

module Activities
  class CreateGithubIssueActivity < BaseActivity
    activity_name "CreateGithubIssue"
    SHELL_ISSUE_CREATION_ATTEMPT_PATTERN = /
      \A
      (?:bash|sh)\s+-lc\s+
      (?:
        ["']
      )?
      (?:
        [A-Za-z_][A-Za-z0-9_]*=
        (?:
          "[^"]*" |
          '[^']*' |
          [^\s"'\\]+
        )
        \s+
      )*
      \bcurl\b
      (?=.*?(?:-X\s+POST|--request\s+POST))
      (?=.*?\/repos\/[^\/\s]+\/[^\/\s]+\/issues(?:(?=[\s"'?\\])|\z))
      .*$
    /imx
    BARE_ISSUE_CREATION_ATTEMPT_PATTERN = /
      \A
      \bcurl\b
      (?=.*?(?:-X\s+POST|--request\s+POST))
      (?=.*?\/repos\/[^\/\s]+\/[^\/\s]+\/issues(?:(?=[\s"'?\\])|\z))
      .*$
    /imx
    ISSUE_CREATION_FAILURE_PATTERNS = [
      /ActiveRecord::PendingMigrationError/,
      /Upstream request failed/i,
      /\b500\s+Internal\s+Server\s+Error\b/i,
      /\b502\s+Bad\s+Gateway\b/i
    ].freeze
    ISSUE_CREATION_RAW_FAILURE_LINE_PATTERNS = [
      /\AHTTP\/\d(?:\.\d+)?\s+\d{3}\b/i,
      /\A(?:HTTP\/\d(?:\.\d+)?\s+)?500\s+Internal\s+Server\s+Error\b/i,
      /\A(?:HTTP\/\d(?:\.\d+)?\s+)?502\s+Bad\s+Gateway\b/i,
      /\AActiveRecord::PendingMigrationError\b/,
      /\AUpstream request failed\b/i,
      /\A(?:curl|gh):/i,
      /\A\s*\{.*"error"\s*:/i
    ].freeze
    ISSUE_CREATION_FAILURE_LOG_BATCH_SIZE = 200
    ISSUE_CREATION_FAILURE_CONTEXT_LINES = 8

    def execute(input)
      agent_run_id = input[:agent_run_id]
      upstream_issue = input[:upstream_issue]
      body_override = input[:body_override]
      agent_run = AgentRun.find(agent_run_id)
      return result(agent_run) if agent_run.finished?

      track_phase(agent_run_id: agent_run_id, phase_key: "create_github_issue", phase_group: "post", agent_run: agent_run) do
        project = agent_run.project

        client = project.github_token.client
        summary = agent_run.agent_summary_with_stderr_fallback
        validate_issue_creation_attempt!(agent_run)
        title, llm_generated_title = extract_title(summary, agent_run.custom_prompt)
        body = body_override.present? ? issue_body(body_override) : issue_body(summary)
        resolved_dependencies = ProjectConventions::IssueDependencies.convention_value(project)
        body = append_dependency_text(body, upstream_issue, project: project, resolved: resolved_dependencies) if upstream_issue
        body = append_blocked_by_text(body, agent_run, project: project, resolved: resolved_dependencies) if agent_run.blocked_by_issue_ids.present?

        issue_labels = project.auto_add_labels_enabled? ? [ project.generated_label_name ] : []
        priority_label = priority_label_for(agent_run)
        issue_labels << priority_label if priority_label.present?

        gh_issue = client.create_issue(
          project.full_name,
          title: title,
          body: body,
          labels: issue_labels
        )

        completed = agent_run.complete!(issue_url: gh_issue.html_url, issue_number: gh_issue.number)
        unless completed
          logger.info(
            message: "agent_execution.github_issue_completion_skipped",
            agent_run_id: agent_run_id,
            status: agent_run.reload.status,
            issue_url: gh_issue.html_url
          )
        end

        reconcile_created_issue(agent_run, project, gh_issue, upstream_issue: upstream_issue, title: title, llm_generated_title: llm_generated_title)

        ProcessRunQueueJob.perform_later if completed

        { agent_run_id: agent_run_id, issue_url: gh_issue.html_url, issue_number: gh_issue.number }
      end
    end

    private

    def result(agent_run)
      {
        agent_run_id: agent_run.id,
        issue_url: agent_run.created_issue_url,
        issue_number: agent_run.created_issue_number
      }
    end

    # Returns [title, llm_generated] where llm_generated indicates whether
    # the title was produced by the LLM title-generation prompt.
    def extract_title(summary, _custom_prompt = nil)
      # Try first markdown heading (any level) from agent output
      if summary.present?
        heading = summary[/^#+\s+(.+)$/, 1]&.sub(/\s*#+\s*$/, "")&.strip
        if heading.present?
          return [ heading.truncate(Llm::GenerateIssueTitle::MAX_TITLE_LENGTH), false ]
        end
      end

      # Fall back to LLM-generated title from agent output
      llm_title = Llm::GenerateIssueTitle.call(summary: summary)
      return [ llm_title, true ] if llm_title.present?

      # Last resort
      [ "Agent analysis", false ]
    end

    def issue_body(summary)
      if summary.present?
        summary.truncate(50_000)
      else
        "This issue was automatically generated by [Paid](https://github.com/viamin/paid)."
      end
    end

    def priority_label_for(agent_run)
      return nil if agent_run.priority_tier.blank?

      agent_run.project.priority_label_for(agent_run.priority_tier)
    end

    def validate_issue_creation_attempt!(agent_run)
      return unless failed_issue_creation_attempt?(agent_run)

      agent_run.log!(
        "system",
        "Refused fallback issue creation because the agent already attempted and failed to create the GitHub issue"
      )

      raise Temporalio::Error::ApplicationError.new(
        "Agent already attempted and failed to create the GitHub issue; refusing fallback issue creation",
        type: "IssueDraftInvalid",
        non_retryable: true
      )
    end

    def failed_issue_creation_attempt?(agent_run)
      log_lines = []
      stream_states = Hash.new { |states, log_type| states[log_type] = { buffer: +"" } }

      agent_run.agent_run_logs
        .where(log_type: %w[stderr stdout])
        .select(:id, :log_type, :content)
        .find_in_batches(batch_size: ISSUE_CREATION_FAILURE_LOG_BATCH_SIZE) do |batch|
          batch.sort_by(&:id).each do |log|
            append_log_lines!(log_lines, stream_states[log.log_type], log)
          end
        end

      stream_states.each_value do |state|
        flush_log_line!(log_lines, state)
      end

      return false if log_lines.empty?

      failed_issue_creation_attempt_in_lines?(log_lines.sort_by { |entry| [ entry[:id], entry[:sequence] ] })
    end

    def issue_creation_attempt_line?(line)
      shell_issue_creation_attempt_line?(line) || bare_issue_creation_attempt_line?(line)
    end

    def shell_issue_creation_attempt_line?(line)
      line.match?(SHELL_ISSUE_CREATION_ATTEMPT_PATTERN)
    end

    def bare_issue_creation_attempt_line?(line)
      line.match?(BARE_ISSUE_CREATION_ATTEMPT_PATTERN)
    end

    def markdown_code_fence_line?(line)
      line.start_with?("```")
    end

    def append_log_lines!(log_lines, state, log)
      if state[:buffer].present? && !chunk_continues_previous_line?(state[:buffer], log.content)
        flush_log_line!(log_lines, state)
      end

      state[:line_id] ||= log.id
      state[:log_type] ||= log.log_type
      state[:buffer] << log.content
      state[:last_id] = log.id

      while (newline_index = state[:buffer].index("\n"))
        emit_log_line!(log_lines, state, state[:buffer].slice!(0, newline_index + 1).delete_suffix("\n"))
        reset_emitted_line_state!(state, log)
      end
    end

    def flush_log_line!(log_lines, state)
      return if state[:buffer].blank?

      emit_log_line!(log_lines, state, state[:buffer])
      state[:buffer] = +""
      state[:line_id] = nil
      state[:log_type] = nil
    end

    def emit_log_line!(log_lines, state, line)
      log_lines << {
        id: state[:line_id] || state[:last_id],
        sequence: log_lines.length,
        log_type: state[:log_type],
        line: line
      }
    end

    def reset_emitted_line_state!(state, log)
      if state[:buffer].present?
        state[:line_id] = log.id
        state[:log_type] = log.log_type
      else
        state[:line_id] = nil
        state[:log_type] = nil
      end
    end

    def chunk_continues_previous_line?(chunk, next_chunk)
      return false if chunk.end_with?("\n")

      line = chunk.lines.last.to_s
      next_line = next_chunk.lines.first.to_s
      stripped_line = line.strip
      return false if line.empty?

      stripped_line.match?(/\A`{1,2}\z/) ||
        incomplete_issue_creation_attempt_fragment?(stripped_line, next_line.strip)
    end

    def incomplete_issue_creation_attempt_fragment?(line, next_line = nil)
      return false unless issue_creation_attempt_fragment_prefix?(line)

      combined_line = [ line, next_line.presence ].compact.join

      !issue_creation_attempt_line?(line) && issue_creation_attempt_line?(combined_line)
    end

    def issue_creation_attempt_fragment_prefix?(line)
      line.match?(/\A(?:bash|sh)\s+-lc\s+(?:["'])?(?:(?:[A-Za-z_][A-Za-z0-9_]*=(?:"[^"]*"|'[^']*'|[^\s"'\\]+))\s+)*(?:\bcur(?:l\b?)?)?/im) ||
        line.match?(/\Acur(?:l\b?)?/i)
    end

    def failed_issue_creation_attempt_in_lines?(log_lines)
      inside_code_fence = Hash.new(false)

      log_lines.each_with_index.any? do |entry, index|
        stripped_line = entry[:line].strip
        log_type = entry[:log_type]

        if markdown_code_fence_line?(stripped_line)
          inside_code_fence[log_type] = !inside_code_fence[log_type]
          next false
        end

        next false if inside_code_fence[log_type]
        next false unless issue_creation_attempt_line?(stripped_line)

        failure_lines = log_lines[index + 1, ISSUE_CREATION_FAILURE_CONTEXT_LINES].to_a.map { |line| line[:line] }
        failure_context = failure_lines.join("\n")
        next false if failure_context.blank?
        next false if bare_issue_creation_attempt_line?(stripped_line) &&
          !bare_issue_creation_attempt_output?(failure_lines)

        issue_creation_failure_marker?(failure_context)
      end
    end

    def bare_issue_creation_attempt_output?(failure_lines)
      first_output_line = failure_lines
        .map(&:strip)
        .reject(&:blank?)
        .drop_while { |line| issue_creation_command_continuation_line?(line) }
        .first
      return false if first_output_line.blank?

      ISSUE_CREATION_RAW_FAILURE_LINE_PATTERNS.any? { |pattern| pattern.match?(first_output_line) }
    end

    def issue_creation_command_continuation_line?(line)
      line.match?(/\A(?:-[A-Za-z]|--[A-Za-z]|\\)/)
    end

    def issue_creation_failure_marker?(text)
      ISSUE_CREATION_FAILURE_PATTERNS.any? { |pattern| pattern.match?(text) }
    end

    def append_dependency_text(body, upstream_issue, project:, resolved: nil)
      resolved ||= ProjectConventions::IssueDependencies.convention_value(project)
      dep_line = ProjectConventions::IssueDependencies.blocked_by_line(
        project: project,
        repo: upstream_issue[:target_repo],
        github_number: upstream_issue[:issue_number],
        resolved:
      )
      append_dependency_lines(body, [ dep_line ], project: project, resolved:)
    end

    def append_blocked_by_text(body, agent_run, project:, resolved: nil)
      blocked_issues = agent_run.project.issues
        .where(id: agent_run.blocked_by_issue_ids, github_state: "open")
        .order(:github_number)
      return body if blocked_issues.empty?

      resolved ||= ProjectConventions::IssueDependencies.convention_value(project)
      dep_lines = blocked_issues.map do |issue|
        ProjectConventions::IssueDependencies.depends_on_line(
          project:,
          github_number: issue.github_number,
          resolved:
        )
      end
      append_dependency_lines(body, dep_lines, project: project, resolved:)
    end

    def append_dependency_lines(body, dep_lines, project:, resolved: nil)
      return body if dep_lines.empty?

      heading = ProjectConventions::IssueDependencies.heading(project: project, resolved:)
      dep_text = dep_lines.map { |line| "- #{line}" }.join("\n")

      if body.include?(heading)
        "#{body}\n#{dep_text}"
      else
        "#{body}\n\n#{heading}\n\n#{dep_text}"
      end
    end

    def reconcile_created_issue(agent_run, project, gh_issue, upstream_issue:, title: nil, llm_generated_title: false)
      # Reconcile even when cancellation wins the complete! lock, because the
      # GitHub issue already exists and should not be left orphaned.
      sync_issue_record(project, gh_issue)
      record_cross_repo_issue(agent_run, project.full_name, gh_issue, role: "downstream") if upstream_issue

      record_issue_title_metric(project, gh_issue.number, original_text: title) if llm_generated_title

      agent_run.log!("system", "Issue created: #{gh_issue.html_url}")

      logger.info(
        message: "agent_execution.github_issue_created",
        agent_run_id: agent_run.id,
        issue_url: gh_issue.html_url
      )
    end

    def sync_issue_record(project, gh_issue)
      Issues::UpsertFromGithub.call(project: project, github_issue: gh_issue)
    rescue => e
      logger.warn(
        message: "agent_execution.sync_created_issue_failed",
        project_id: project.id,
        issue_number: gh_issue.number,
        error: e.message
      )
    end

    def record_issue_title_metric(project, issue_number, original_text: nil)
      LlmOutputMetrics::Record.call(
        project: project,
        output_type: "issue_title",
        prompt_slug: Llm::GenerateIssueTitle::PROMPT_SLUG,
        source_type: "Issue",
        source_id: issue_number,
        metadata: { "original_text" => original_text }
      )
    rescue StandardError => e
      logger.warn(
        message: "llm_output_metrics.record_issue_title_failed",
        project_id: project.id,
        issue_number: issue_number,
        error: e.message
      )
    end
  end
end

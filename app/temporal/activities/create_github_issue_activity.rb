# frozen_string_literal: true

module Activities
  class CreateGithubIssueActivity < BaseActivity
    activity_name "CreateGithubIssue"

    PAID_GENERATED_LABEL = "paid-generated"

    def execute(input)
      agent_run_id = input[:agent_run_id]
      track_phase(agent_run_id: agent_run_id, phase_key: "create_github_issue", phase_group: "post") do
        agent_run = AgentRun.find(agent_run_id)
        project = agent_run.project

        client = project.github_token.client
        summary = agent_run.agent_summary
        title = extract_title(summary, agent_run.custom_prompt)
        body = issue_body(summary)

        gh_issue = client.create_issue(
          project.full_name,
          title: title,
          body: body,
          labels: [ PAID_GENERATED_LABEL ]
        )

        sync_issue_record(project, gh_issue)

        agent_run.complete!(issue_url: gh_issue.html_url, issue_number: gh_issue.number)

        agent_run.log!("system", "Issue created: #{gh_issue.html_url}")

        logger.info(
          message: "agent_execution.github_issue_created",
          agent_run_id: agent_run_id,
          issue_url: gh_issue.html_url
        )

        ProcessRunQueueJob.perform_later

        { agent_run_id: agent_run_id, issue_url: gh_issue.html_url, issue_number: gh_issue.number }
      end
    end

    private

    def extract_title(summary, _custom_prompt = nil)
      # Try first markdown heading (any level) from agent output
      if summary.present?
        heading = summary[/^#+\s+(.+)$/, 1]&.sub(/\s*#+\s*$/, "")&.strip
        return heading.truncate(Llm::GenerateIssueTitle::MAX_TITLE_LENGTH) if heading.present?
      end

      # Fall back to LLM-generated title from agent output
      llm_title = Llm::GenerateIssueTitle.call(summary: summary)
      return llm_title if llm_title.present?

      # Last resort
      "Agent analysis"
    end

    def issue_body(summary)
      if summary.present?
        summary.truncate(50_000)
      else
        "This issue was automatically generated by [Paid](https://github.com/viamin/paid)."
      end
    end

    def sync_issue_record(project, gh_issue)
      issue = project.issues.find_or_initialize_by(github_issue_id: gh_issue.id)
      issue.update!(
        github_number: gh_issue.number,
        title: gh_issue.title,
        body: gh_issue.body,
        github_creator_login: gh_issue.user&.login || "unknown",
        github_state: gh_issue.state,
        labels: (gh_issue.labels || []).map { |l| l.respond_to?(:name) ? l.name : l.to_s },
        is_pull_request: false,
        github_created_at: gh_issue.created_at,
        github_updated_at: gh_issue.updated_at
      )
    rescue => e
      logger.warn(
        message: "agent_execution.sync_created_issue_failed",
        project_id: project.id,
        issue_number: gh_issue.number,
        error: e.message
      )
    end
  end
end
